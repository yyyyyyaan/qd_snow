"""Build the multi-context (context-switching) version of the PE-array decoder.

    python fpga_flow/make_pearray_ctx.py

Reads  design/snowflake/snowflake_pe.sv
       design/snowflake/snowflake_edge.sv
       design/snowflake/snowflake_pe_array.sv          (verified, single context)
Writes design/snowflake/snowflake_pe_ctx.sv
       design/snowflake/snowflake_edge_ctx.sv
       design/snowflake/snowflake_pe_array_ctx.sv

Why a generator and not hand edits: the transformation is mechanical (every
state register gets one copy per context, every access is indexed by the
selected context, the combinational logic is untouched), and keeping it
mechanical means the verified single-context sources stay the reference.

Context switching in the PE array is the cheap form, and that is the whole
point of building the array: each PE only muxes *its own* state instead of the
flat design's array-wide read multiplexers, and the neighbour wires already
carry the selected context's values because every PE output is muxed locally.
In the flat core the same feature measured only 7-9% area saving.

Debugging notes worth keeping (both were silent in lint and only showed up as
wrong/z traces):
  * an unpacked net array declared without an element width defaults to 1 bit
    and truncates the state (that killed the first flat prototype);
  * using a signal before its declaration creates an implicit 1-bit net, so
    the control block below is deliberately placed BEFORE the generate section
    that references it.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "Helios_scalable_QEC-main", "Helios_scalable_QEC-main"))
DSN = os.path.join(REPO, "design", "snowflake")

HDR = ("//=========================================================================\n"
       "// GENERATED by fpga_flow/make_pearray_ctx.py -- do not edit by hand;\n"
       "// edit the generator or the single-context sources instead.\n"
       "//\n"
       "// Multi-context version: every state register has one copy per context,\n"
       "// the datapath is shared and time multiplexed, and each PE muxes only its\n"
       "// own state (the cheap form of context switching).\n"
       "//=========================================================================\n")

CTX_PARAM = """`ifdef SNOW_CTX1
    parameter integer NCTX = 1
`else
    parameter integer NCTX = 2
`endif
"""

CTXW_PORT = "[((NCTX>1)?$clog2(NCTX):1)-1:0]"

# Optional probe: SNOW_PE_RAM=1 asks Vivado to map the per-context state to
# distributed RAM ("state in a small RAM, context as an address bit", the Helios
# form).  Whether that is even possible depends on NCTX: with NCTX=2 the "RAM" is
# two entries deep, so Vivado folds it back into a 2:1 multiplexer and the
# attribute changes nothing.  It only becomes a real RAM for larger NCTX, which
# is exactly the scaling statement we want to measure rather than assume.
RAM_ATTR = ('(* ram_style = "distributed" *) ' if os.environ.get("SNOW_PE_RAM") else '')

CTRL_BLOCK = """  localparam integer CTXW = (NCTX > 1) ? $clog2(NCTX) : 1;

  // ---- per-context control state (declared BEFORE the generate section: a
  //      use-before-declaration would create an implicit 1-bit net) ----
  reg [2:0]      stage    [0:NCTX-1];
  reg [7:0]      step_cnt [0:NCTX-1];
  reg            run      [0:NCTX-1];
  reg [SNOW_NSYN-1:0] syn_buf [0:NCTX-1];
  reg [CTXW-1:0] ctx_sel;
  reg [CTXW-1:0] dbg_ctx_r;
  reg [CTXW-1:0] cur;                 // context that owns the datapath
  reg [CTXW-1:0] hold;
  reg            hold_valid;
  reg            ctx_found;
  integer        ctx_scan, c;

  assign dbg_ctx = dbg_ctx_r;

  // Arbiter: NON-PREEMPTIVE round robin.  Once a context owns the datapath it
  // keeps it until its round finishes (the observation buses are combinational
  // on ctx_sel, so preempting mid-round would sample the new context's state
  // under the old context's stage and corrupt the trace), then the lowest-index
  // ready context is served.  A stalled/late context therefore does not
  // interrupt the running one -- it simply waits, which is exactly the
  // stall-filling behaviour being measured.  The extra drain cycle keeps
  // pointing at a context for one clock after it finishes so its last step is
  // still sampled correctly.
  always @(*) begin
    if (hold_valid) begin
      ctx_sel   = hold;
      ctx_found = 1'b0;
    end else if (run[cur]) begin
      ctx_sel   = cur;
      ctx_found = 1'b1;
    end else begin
      ctx_sel   = {CTXW{1'b0}};
      ctx_found = 1'b0;
      for (ctx_scan = 0; ctx_scan < NCTX; ctx_scan = ctx_scan + 1) begin
        if (!ctx_found && run[ctx_scan]) begin
          ctx_sel   = ctx_scan;
          ctx_found = 1'b1;
        end
      end
    end
  end

  wire [2:0] stage_sel = stage[ctx_sel];
  wire       busy_sel  = any_c_busy;

"""

CTRL_FSM = """  // ---- per-context stage machine (same stages as the flat core) ----
  always @(posedge clk) begin
    if (reset) begin
      for (c = 0; c < NCTX; c = c + 1) begin
        stage[c]    <= ST_IDLE;
        step_cnt[c] <= 8'd0;
        run[c]      <= 1'b0;
      end
      done <= {NCTX{1'b0}};
      hold_valid <= 1'b0;
      hold <= {CTXW{1'b0}};
      cur <= {CTXW{1'b0}};
      dbg_ctx_r <= {CTXW{1'b0}};
      dbg_stage <= ST_IDLE;
      dbg_step <= 8'd0;
      dbg_valid <= 1'b0;
      commit_onehot <= {(NCTX*SNOW_NCOMMIT){1'b0}};
    end else begin
      dbg_valid <= 1'b0;
      hold_valid <= 1'b0;                 // set again below when a context finishes
      done <= {NCTX{1'b0}};               // one-clock pulses for every context
      commit_onehot <= {(NCTX*SNOW_NCOMMIT){1'b0}};

      // start handling: latch the context's syndrome and mark it ready
      for (c = 0; c < NCTX; c = c + 1) begin
        if (start[c] && !run[c]) begin
          run[c]      <= 1'b1;
          stage[c]    <= ST_DROP;
          step_cnt[c] <= 8'd1;
          syn_buf[c]  <= syndrome[c*SNOW_NSYN +: SNOW_NSYN];
        end
      end

      // non-preemptive ownership: when nobody owns the datapath, take the
      // context the arbiter selected
      if (!run[cur] && ctx_found) cur <= ctx_sel;

      case (stage_sel)
        ST_IDLE: ;
        ST_DROP: begin stage[ctx_sel] <= ST_GW; step_cnt[ctx_sel] <= 8'd1; end
        ST_GW:   begin stage[ctx_sel] <= ST_MW; step_cnt[ctx_sel] <= 8'd1; end
        ST_MW:   begin
                   if (!busy_sel) begin
                     if (ONE_ONE) begin
                       stage[ctx_sel] <= ST_IDLE; step_cnt[ctx_sel] <= 8'd0;
                       done[ctx_sel] <= 1'b1; run[ctx_sel] <= 1'b0;
                       hold <= ctx_sel; hold_valid <= 1'b1;
                     end else begin
                       stage[ctx_sel] <= ST_GH; step_cnt[ctx_sel] <= 8'd1;
                     end
                   end else step_cnt[ctx_sel] <= step_cnt[ctx_sel] + 8'd1;
                 end
        ST_GH:   begin stage[ctx_sel] <= ST_MH; step_cnt[ctx_sel] <= 8'd1; end
        ST_MH:   begin
                   if (!busy_sel) begin
                     stage[ctx_sel] <= ST_IDLE; step_cnt[ctx_sel] <= 8'd0;
                     done[ctx_sel] <= 1'b1; run[ctx_sel] <= 1'b0;
                     hold <= ctx_sel; hold_valid <= 1'b1;
                   end else step_cnt[ctx_sel] <= step_cnt[ctx_sel] + 8'd1;
                 end
        default: stage[ctx_sel] <= ST_IDLE;
      endcase

      if (ctx_found && (stage_sel != ST_IDLE)) begin
        dbg_stage <= stage_sel;
        dbg_step  <= step_cnt[ctx_sel];
        dbg_ctx_r <= ctx_sel;
        dbg_valid <= 1'b1;
        if (stage_sel == ST_DROP)
          for (c = 0; c < SNOW_NCOMMIT; c = c + 1)
            commit_onehot[ctx_sel*SNOW_NCOMMIT + c] <= commit_bits[c];
      end
    end
  end
"""


def read(name):
    with open(os.path.join(DSN, name), encoding="utf-8", errors="ignore") as fh:
        return fh.read().replace("\r\n", "\n")


def write(name, txt):
    with open(os.path.join(DSN, name), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HDR + txt)
    print("wrote", name)


def transform_pe(src):
    i = src.index("  // ---------- state (all local to this node) ----------")
    j = src.index("  // ---------- combinational next state ----------")
    A, MID, C = src[:i], src[i:j], src[j:]
    # MID holds the declarations (replaced below) AND the output assigns, which
    # must be kept -- dropping them leaves every PE output undriven (z), which
    # is exactly what the first version of this generator did.
    assigns = MID[MID.index("  assign "):]

    A = A.replace("module snowflake_pe #(", "module snowflake_pe_ctx #(")
    A = A.replace("""    parameter integer SYN_IDX   = -1       // -1 = this node is not a syndrome node
) (""",
"""    parameter integer SYN_IDX   = -1,      // -1 = this node is not a syndrome node
""" + CTX_PARAM + """) (""")
    A = A.replace("""    input  wire [2:0]  stage,""",
                  """    input  wire [2:0]  stage,
    input  wire %s ctx,   // context that owns the datapath now""" % CTXW_PORT)

    B = """  // ---------- state (all local to this node, one copy per context) ----------
  localparam integer CTXW = (NCTX > 1) ? $clog2(NCTX) : 1;
  %sreg [SNOW_CID_W-1:0] cid      [0:NCTX-1];
  %sreg                  active   [0:NCTX-1];
  %sreg                  whole    [0:NCTX-1];
  %sreg                  defect   [0:NCTX-1];
  %sreg                  grown    [0:NCTX-1];
  %sreg                  unrooted [0:NCTX-1];
  %sreg                  busy     [0:NCTX-1];
  %sreg [SNOW_PTR_W-1:0] ptr      [0:NCTX-1];
  integer              c;

""" % ((RAM_ATTR,) * 8)

    for nm in ("cid", "active", "whole", "defect", "ptr", "grown", "unrooted", "busy"):
        C = re.sub(r"(?<![\w])%s(?![\w])" % nm, "%s[ctx]" % nm, C)
        assigns = re.sub(r"(?<![\w])%s(?![\w])" % nm, "%s[ctx]" % nm, assigns)
    for bad in ("n_cid", "best_cid", "o_cid", "ab_cid", "nb_cid", "pe_cid",
                "n_active", "n_whole", "n_defect", "n_grown", "n_unrooted", "n_ptr",
                "o_active", "o_whole", "o_defect", "o_grown", "o_unrooted", "o_busy", "o_ptr",
                "ab_active", "ab_whole", "ab_defect", "ab_ptr", "busy_c", "det_def"):
        C = C.replace(bad + "[ctx]", bad)
        assigns = assigns.replace(bad + "[ctx]", bad)

    C = C.replace("""    if (reset) begin
      cid[ctx]      <= ID[SNOW_CID_W-1:0];
      active[ctx]   <= 1'b0;
      whole[ctx]    <= 1'b1;
      defect[ctx]   <= 1'b0;
      ptr[ctx]      <= SNOW_PTR_C;
      grown[ctx]    <= 1'b0;
      unrooted[ctx] <= 1'b0;
      busy[ctx]     <= 1'b0;
    end else if (stage != ST_IDLE) begin""",
"""    if (reset) begin
      for (c = 0; c < NCTX; c = c + 1) begin
        cid[c]      <= ID[SNOW_CID_W-1:0];
        active[c]   <= 1'b0;
        whole[c]    <= 1'b1;
        defect[c]   <= 1'b0;
        ptr[c]      <= SNOW_PTR_C;
        grown[c]    <= 1'b0;
        unrooted[c] <= 1'b0;
        busy[c]     <= 1'b0;
      end
    end else if (stage != ST_IDLE) begin""")
    return A + B + assigns + C


def transform_edge(src):
    txt = src.replace("module snowflake_edge (", "module snowflake_edge_ctx #(\n" + CTX_PARAM + ") (")
    txt = txt.replace("""    input  wire [2:0] stage,""",
                      """    input  wire [2:0] stage,
    input  wire %s ctx,""" % CTXW_PORT)
    txt = txt.replace("""    output reg  [1:0] growth,
    output reg        ecorr
);""",
"""    output wire [1:0] growth,      // selected context
    output wire       ecorr
);
  %sreg [1:0] growth_mem [0:NCTX-1];
  %sreg       ecorr_mem  [0:NCTX-1];
  integer   c;

  assign growth = growth_mem[ctx];
  assign ecorr  = ecorr_mem[ctx];""" % (RAM_ATTR, RAM_ATTR))
    txt = re.sub(
        r"  wire \[1:0\] +inc += \{1'b0, u_pulse\} \+ \{1'b0, v_pulse\};\n"
        r"  wire \[1:0\] +grown_n = \(growth \+ inc > 2'd2\) \? 2'd2 : \(growth \+ inc\);",
        "  wire [1:0] growth_c = growth_mem[ctx];\n"
        "  wire       ecorr_c  = ecorr_mem[ctx];\n"
        "  wire [1:0] inc      = {1'b0, u_pulse} + {1'b0, v_pulse};\n"
        "  wire [1:0] grown_n  = (growth_c + inc > 2'd2) ? 2'd2 : (growth_c + inc);", txt)
    txt = txt.replace("""    if (reset) begin
      growth <= 2'd0;
      ecorr  <= 1'b0;
    end else if (stage == ST_DROP) begin
      growth <= above_growth;
      ecorr  <= above_ecorr;
    end else if (growing) begin
      if (growth < 2'd2) growth <= grown_n;
    end else if (merging) begin
      if (flip_u ^ flip_v) ecorr <= ecorr ^ 1'b1;
    end""",
"""    if (reset) begin
      for (c = 0; c < NCTX; c = c + 1) begin
        growth_mem[c] <= 2'd0;
        ecorr_mem[c]  <= 1'b0;
      end
    end else if (stage == ST_DROP) begin
      growth_mem[ctx] <= above_growth;
      ecorr_mem[ctx]  <= above_ecorr;
    end else if (growing) begin
      if (growth_c < 2'd2) growth_mem[ctx] <= grown_n;
    end else if (merging) begin
      if (flip_u ^ flip_v) ecorr_mem[ctx] <= ecorr_c ^ 1'b1;
    end""")
    return txt


def transform_array(src):
    A_END = "  assign all_busy    = |busy_vec;\n  assign any_c_busy  = |busy_c_vec;\n"
    GEN_START = "  genvar n, e, d;"
    CTRL_START = "  // ---------------- stage controller (same as the flat core) ----------------"
    i = src.index(A_END) + len(A_END)
    j = src.index(GEN_START)
    k = src.index(CTRL_START)
    A, B, _ = src[:i], src[j:k], src[k:]

    A = A.replace("module snowflake_pe_array #(", "module snowflake_pe_array_ctx #(")
    A = A.replace("""`ifdef SNOW_NO_OBS
    , parameter integer DEBUG_OBS = 0
`else
    , parameter integer DEBUG_OBS = 1
`endif
) (""",
"""`ifdef SNOW_NO_OBS
    , parameter integer DEBUG_OBS = 0
`else
    , parameter integer DEBUG_OBS = 1
`endif
`ifdef SNOW_CTX1
    , parameter integer NCTX = 1
`else
    , parameter integer NCTX = 2
`endif
) (""")
    A = A.replace("""    input  wire        start,
    input  wire [SNOW_NSYN-1:0] syndrome,
    output reg         done,""",
"""    input  wire [NCTX-1:0] start,
    input  wire [NCTX*SNOW_NSYN-1:0] syndrome,
    output reg  [NCTX-1:0] done,""")
    A = A.replace("    output reg  [SNOW_NCOMMIT-1:0] commit_onehot,",
                  "    output reg  [NCTX*SNOW_NCOMMIT-1:0] commit_onehot,")
    A = A.replace("""    output reg  [2:0]  dbg_stage,""",
                  """    output wire %s dbg_ctx,
    output reg  [2:0]  dbg_stage,""" % CTXW_PORT)
    A = A.replace("""  reg [2:0] stage;
  reg [7:0] step_cnt;""",
"""  // (per-context stage/step_cnt/run live in the control block below)""")

    # generate section: PE / edge instances take the selected context
    B = B.replace("      assign pe_syn_bit[n] = IS_SYN ? syndrome[SIDX] : 1'b0;",
                  "      assign pe_syn_bit[n] = IS_SYN ? syn_buf[ctx_sel][SIDX] : 1'b0;")
    B = B.replace("      snowflake_pe #(", "      snowflake_pe_ctx #(")
    B = B.replace("        .IS_TOP(TOP), .IS_BOT(BOT), .SYN_IDX(SIDX)\n      ) pe_i (",
                  "        .IS_TOP(TOP), .IS_BOT(BOT), .SYN_IDX(SIDX), .NCTX(NCTX)\n      ) pe_i (")
    B = B.replace("        .clk(clk), .reset(reset), .stage(stage), .syn_bit(pe_syn_bit[n]),",
                  "        .clk(clk), .reset(reset), .stage(stage_sel), .ctx(ctx_sel),\n"
                  "        .syn_bit(pe_syn_bit[n]),")
    B = B.replace("      snowflake_edge ed_i (", "      snowflake_edge_ctx #(.NCTX(NCTX)) ed_i (")
    B = B.replace("        .clk(clk), .reset(reset), .stage(stage),",
                  "        .clk(clk), .reset(reset), .stage(stage_sel), .ctx(ctx_sel),")

    return A + CTRL_BLOCK + B + "\n" + CTRL_FSM + "\nendmodule\n"


def main():
    write("snowflake_pe_ctx.sv", transform_pe(read("snowflake_pe.sv")))
    write("snowflake_edge_ctx.sv", transform_edge(read("snowflake_edge.sv")))
    write("snowflake_pe_array_ctx.sv", transform_array(read("snowflake_pe_array.sv")))


if __name__ == "__main__":
    main()
