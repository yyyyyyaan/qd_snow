#=====================================================================
# board_ooc.ps1 -- out-of-context Vivado build of the BOARD TOP.
#
# It answers three questions the bring-up image needs before any board exists:
#   1. does the periphery (AXI slave + trace buffer + reset tree) plus the array
#      FIT the Z-7020, and how many BRAMs does the trace buffer take?
#   2. does the whole PL close timing at the clock we intend to run (WNS >= 0)?
#   3. what is the real per-round time budget: cycles/round from the regression
#      x the achieved period?
#
# It pins a FRESH graph header before the run.  That is not cosmetic: the
# `fpga_flow/graphs/*.svh` pins from before 2026-09-23 predate
# `SNOW_PTR_DOWN_MASK` (the circuit-level pointer fix, report 6.32) and the RTL
# now requires that symbol, so pinning a stale copy fails to elaborate -- or,
# worse, a pin from before the fix would be a silently different decoder.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File fpga_flow\board_ooc.ps1 `
#       -Code rotated -D 3 -Slices 2 -Period 20 -Mode impl
#=====================================================================
param(
  [string] $Code   = 'rotated',
  [int]    $D      = 3,
  [int]    $Slices = 2,
  [string] $Dirs   = 'all',
  [string] $Noise  = 'phenomenological',
  [string] $Part   = 'xc7z020clg484-1',
  [double] $Period = 20.0,
  [string] $Mode   = 'impl',        # impl | synth
  [int]    $MaxRec = 128,
  [string] $Csv    = '',
  # -Rev tags a build revision.  The sweep tag is
  #   <prefix><code>_d<d>_<sched>[_<defs suffix>]_<part>[_p<period>]
  # so two runs of the SAME config at the same period collide: the second one
  # overwrites the first one's log while the CSV keeps both rows, and the first
  # row then points at the second run's report.  Adding a marker define is how
  # every other flow in this repo disambiguates (`-ExtraDefs SNOW_BUSYREG`,
  # `-Rev v2`, ...); it also means the revision is visible in the tag.
  [string] $Rev    = ''
)
$ErrorActionPreference = 'Continue'
$Flow = $PSScriptRoot
$Ws   = Split-Path -Parent $Flow
$Repo = Join-Path $Ws 'Helios_scalable_QEC-main\Helios_scalable_QEC-main'

# ---- 1. fresh tables (and a fresh pin, see the header) ----------------------
Push-Location (Join-Path $Repo 'build_scripts')
python generate_snowflake.py --code $Code --d $D --dirs $Dirs --noise $Noise | Out-Null
Pop-Location
python (Join-Path $Flow 'make_lattice_sim.py') --code $Code --d $D --slices $Slices `
       --dirs $Dirs --noise $Noise | Out-Null
if ($LASTEXITCODE -ne 0) { Write-Host '[board-ooc] lattice generator FAILED'; exit 1 }
Copy-Item (Join-Path $Repo "design\generated\snowflake_graph_${Code}_d${D}.svh") `
          (Join-Path $Flow "graphs\${Code}_d${D}.svh") -Force
$npin = Join-Path $Flow "graphs\${Code}_d${D}.svh"
$mask = (Select-String -Path $npin -Pattern 'SNOW_PTR_DOWN_MASK' -Quiet)
Write-Host ("[board-ooc] pinned graph {0} (down_mask={1})" -f (Split-Path $npin -Leaf), $mask)
if (-not $mask) { Write-Host '[board-ooc] FATAL: pinned graph has no SNOW_PTR_DOWN_MASK'; exit 1 }

# ---- 2. job line + sweep call ----------------------------------------------
$jobs = Join-Path $Flow 'jobs_board_ooc.txt'
$defs = 'SNOW_LATTICE;SNOW_LAT'
if ($Rev) { $defs += ";SNOW_$Rev" }
@(
  '# generated by board_ooc.ps1 -- the BOARD TOP, one config only.',
  ("{0} {1} 2:1 {2} {3} {4}" -f $Code, $D, $Part, $Period, $defs)
) | Set-Content -Encoding ASCII $jobs

$srcs = @(
  "$Repo\design\snowflake\snowflake_edge.sv",
  "$Repo\design\snowflake\snowflake_pe.sv",
  "$Repo\design\snowflake\snowflake_pe_array_lat1.sv",
  "$Repo\design\board\snowflake_reset_sync.sv",
  "$Repo\design\board\snowflake_trace_capture.sv",
  "$Repo\design\board\snowflake_host_regs.sv",
  "$Repo\design\board\snowflake_board_top.sv"
) -join ';'
if (-not $Csv) { $Csv = Join-Path $Flow 'summary_board.csv' }

Write-Host ("[board-ooc] top=snowflake_board_top part={0} period={1} ns mode={2} maxrec={3}" `
            -f $Part, $Period, $Mode, $MaxRec)
& (Join-Path $Flow 'sweep.ps1') -JobsFile $jobs -Mode $Mode -Top 'snowflake_board_top' `
    -Srcs $srcs -TagPrefix 'board_' -Csv $Csv -Flatten 'none'
Write-Host "[board-ooc] rows -> $Csv ; reports -> fpga_flow\logs\"
