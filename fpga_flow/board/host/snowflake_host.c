/*=============================================================================
 * snowflake_host.c -- PS (Cortex-A9) bring-up host for the Snowflake decoder.
 *
 * WHAT THIS IS
 * ------------
 * The software half of D8: make the board replay the SAME 12-round stimulus the
 * RTL regressions use and read the `obs_*` trace back out of the PL, so the
 * result can be compared line for line against fpga_flow/evidence/golden_*.txt.
 *
 * It is the C twin of fpga_flow/board_records_to_trace.py, which is the
 * EXECUTABLE specification of the record layout: that script has been run
 * against real captured hardware-path records and reproduces the golden line for
 * line (fpga_flow/evidence/PASS_board_*.txt).  Every field offset below mirrors
 * it; the two places that matter are marked MIRROR.
 *
 * HONESTY NOTE (read before quoting a number from this file)
 * ---------------------------------------------------------
 * This C has NOT been compiled or executed: the development machine has no C
 * toolchain and there is no board yet.  What IS verified is the algorithm it
 * implements -- bit offsets, access order, line format -- verified through the
 * Python twin against captured records.  Treat this as a reviewed transcription
 * and re-check the two MIRROR functions against the Python if either is edited.
 *
 * WHY THERE IS NO ON-BOARD COMPARISON
 * -----------------------------------
 * The comparator is `snowflake_sim/ref/compare_trace.py`, it already runs
 * against the evidence goldens, and it is the SAME tool that judged every RTL
 * and gate-level regression.  A second comparator inside the PS would add an
 * untested code path and prove nothing extra, so the board's job is to dump and
 * the PC's job is to judge.
 *
 * PLATFORM
 * --------
 * Xilinx standalone (Vitis), Cortex-A9, no OS.  Needs snowflake_board_map.h
 * (generated by fpga_flow/make_board_map.py) and the BSP's xil_io.h /
 * xil_printf.h.  SNOW_BASE must match the block design's Address Editor entry
 * for M_AXI_GP0 (0x43C0_0000 for slot 0 in the default mapping).
 *
 * BRING-UP PROCEDURE
 * ------------------
 *   1. program the PL bitstream, start this program;
 *   2. it prints the ID block: check it against the map the software was
 *      generated for (nn/ne/ncommit/words) -- this is the "right bitstream?"
 *      question, answered from the PL itself;
 *   3. it runs the 12 rounds and prints, per round, `# round=<k> records=<n>
 *      cycles=<c>` (cycles is the host-visible round latency -- the number the
 *      throughput budget is about);
 *   4. it prints the trace lines (mode 0) or the raw record words (mode 1);
 *   5. on the PC: save the UART log, then
 *        python fpga_flow/board_atouart_check.py --log uart.txt --mode 0|1 ...
 *      (see fpga_flow/board/bringup.md for the exact commands) and compare with
 *      the evidence golden.  That comparison IS the D8 acceptance.
 *===========================================================================*/
#include <stdio.h>
#include "snowflake_board_map.h"

/* ---- platform hooks: the only board-specific lines in this file ---------- */
#define SNOW_BASE        0x43C00000u
#define sn_rd32(off)     Xil_In32((SNOW_BASE + (unsigned)(off)))
#define sn_wr32(off, v)  Xil_Out32((SNOW_BASE + (unsigned)(off)), (unsigned)(v))
#define sn_log           xil_printf

/* 0 = print trace lines (default), 1 = print raw record words */
#define SNOW_MODE        0
/* a round is ~30 cycles; 2e6 polls is ~20 ms and only reached on a hang */
#define SNOW_POLL_LIMIT  2000000u

/* The stimulus.  MUST be the 12 rounds the golden was generated for -- the RTL
 * testbench's `rounds[]`, this array and the golden's own header are the same
 * sequence (see the reset/board docs; a mismatch shows up as an immediate
 * first-line divergence, which is why the flow prints it). */
static const unsigned short ROUNDS[12] = {
  0x0000, 0x0001, 0x0002, 0x0003, 0x0000, 0x0001,
  0x0000, 0x0002, 0x0003, 0x0000, 0x0001, 0x0000
};

static unsigned rec_words[SNOW_TRACE_WORDS];   /* one record; word 0 = bits 0..31 */

/*----------------------------------------------------------------------------
 * MIRROR #1 -- field extraction.  Python:
 *     def get(rec, off, w): return (rec >> off) & ((1 << w) - 1)
 * A record is a BIT STRING of up to ~4000 bits (rotated d5 = 2121 bits = 67
 * words), so it is held as a word array and read bit by bit.  Shifting a C
 * integer would silently lose everything above bit 31 -- which is exactly the
 * class of bug the PL-vs-software layout check exists to catch.
 *--------------------------------------------------------------------------*/
static unsigned sn_field(const unsigned *w, unsigned lo, unsigned nbits)
{
    unsigned v = 0, i;
    for (i = 0; i < nbits; i++) {
        unsigned bit = lo + i;
        v |= ((w[bit >> 5] >> (bit & 31u)) & 1u) << i;
    }
    return v;
}

/*----------------------------------------------------------------------------
 * MIRROR #2 -- record access order.  Writing TRACE_REC latches the record into
 * the read register; every TRACE_DATA read returns the CURRENT word and then
 * ADVANCES TRACE_WIX, wrapping at ID_WORDS.  So: address once, then read the
 * words back to back.  This is the sequence the board path was verified with.
 *--------------------------------------------------------------------------*/
static void sn_fetch_record(unsigned rec)
{
    unsigned i;
    sn_wr32(REG_TRACE_REC, rec);
    for (i = 0; i < SNOW_TRACE_WORDS; i++)
        rec_words[i] = sn_rd32(REG_TRACE_DATA);
}

/* One decode round: syndrome -> clear -> arm -> start -> wait for done.
 * Returns the PL-reported cycle count, 0 on timeout. */
static unsigned sn_run_round(unsigned round, unsigned syn)
{
    unsigned w, st, poll;
    for (w = 0; w < SNOW_SYN_WORDS; w++)
        sn_wr32(REG_SYN_BASE + 4u * w, syn >> (32u * w));
    sn_wr32(REG_CTRL, SNOW_CTRL_TRACE_CLEAR);
    sn_wr32(REG_CTRL, SNOW_CTRL_TRACE_ARM);
    sn_wr32(REG_CTRL, SNOW_CTRL_START);
    for (poll = 0; poll < SNOW_POLL_LIMIT; poll++) {
        st = sn_rd32(REG_STATUS);
        if (st & SNOW_ST_DONE)
            return sn_rd32(REG_CYC_LAST);
    }
    sn_log("FATAL: round %d never finished (STATUS=%08x)\r\n", round, st);
    return 0;
}

/* Is the bitstream the one this software was generated for?  The ID block is
 * read straight out of the PL; `nn/ne/ncommit/nsyn/cid_w/ptr_w/ndir` pin the
 * code, the distance and the noise model without any build stamp to keep in
 * sync.
 *
 * The `#LAYOUT` line is printed in EXACTLY the format the RTL testbench prints
 * and fpga_flow/board_records_to_trace.py parses, so a UART log in mode 1 goes
 * through the very same converter that was verified against captured records
 * (fpga_flow/board_log_check.py --mode 1).  rstlen/rstpulse are hardware
 * parameters software cannot see; they are printed as 0 and are not checked. */
static int sn_check_id(void)
{
    unsigned magic = sn_rd32(REG_ID_MAGIC);
    unsigned wid   = sn_rd32(REG_ID_WID);
    unsigned strd  = sn_rd32(REG_ID_STRIDE);
    int bad = 0;

    sn_log("#LAYOUT magic=%08x nn=%d ne=%d ncommit=%d nsyn=%d cid_w=%d ptr_w=%d "
           "ndir=%d words=%d maxrec=%d hdrw=%d ns=%d es=%d rbits=%d nslot=%d nctx=%d "
           "rstlen=0 rstpulse=0\r\n",
           magic, sn_rd32(REG_ID_NN), sn_rd32(REG_ID_NE), sn_rd32(REG_ID_NCOMMIT),
           sn_rd32(REG_ID_NSYN), wid & 0xFFu, (wid >> 8) & 0xFFu, (wid >> 16) & 0xFFu,
           sn_rd32(REG_ID_WORDS), sn_rd32(REG_ID_MAXREC), sn_rd32(REG_ID_HDRW),
           strd >> 8, strd & 0xFFu, sn_rd32(REG_ID_RBITS),
           sn_rd32(REG_ID_NSLOT), sn_rd32(REG_ID_NCTX));
    sn_log("#ID magic=%08x nn=%d ne=%d ncommit=%d nsyn=%d cid_w=%d ptr_w=%d ndir=%d\r\n",
           magic, sn_rd32(REG_ID_NN), sn_rd32(REG_ID_NE), sn_rd32(REG_ID_NCOMMIT),
           sn_rd32(REG_ID_NSYN), wid & 0xFFu, (wid >> 8) & 0xFFu, (wid >> 16) & 0xFFu);
    if (magic != SNOW_ID_MAGIC) { sn_log("FATAL: ID magic mismatch\r\n"); bad = 1; }
    if (sn_rd32(REG_ID_NN) != SNOW_NN || sn_rd32(REG_ID_NE) != SNOW_NE) {
        sn_log("FATAL: graph size mismatch (software NN=%d NE=%d)\r\n", SNOW_NN, SNOW_NE);
        bad = 1;
    }
    if (sn_rd32(REG_ID_WORDS) != SNOW_TRACE_WORDS) {
        sn_log("FATAL: record length mismatch (software %d words)\r\n", SNOW_TRACE_WORDS);
        bad = 1;
    }
    return bad;
}

/*----------------------------------------------------------------------------
 * Line emission -- byte-identical to tb_snowflake_pe_array_lat1.sv's dump (and
 * therefore to the golden's own text):
 *   T <round> <stage char> <step>
 *   N <n> <cid|R> <active> <whole> <defect> <ptr> <grown> <unrooted>
 *   E <u>-<v> <growth> <ecorr>
 *   P <u>-<v>       only when stage == D and the commit bit is set
 * The flag order inside the 6-bit group is LSB first (bit0 = active ... bit5 =
 * busy); `busy` is captured but not printed, exactly like the RTL testbench.
 * It must be emitted in this order: T, then every N, then every E, then every P.
 *--------------------------------------------------------------------------*/
static const char STAGE_CH[8] = { '?', 'D', 'G', 'M', 'g', 'm', '?', '?' };

#if SNOW_MODE == 1
static void sn_emit(unsigned round, unsigned idx)
{
    unsigned i;
    (void)round;
    sn_log("R %d", idx);
    for (i = 0; i < SNOW_TRACE_WORDS; i++)
        sn_log(" %08x", rec_words[i]);
    sn_log("\r\n");
}
#else
static void sn_emit(unsigned round, unsigned idx)
{
    unsigned n, e, ci, stage, step, cid, ptr, fl, g3, mask;

    (void)idx;
    stage = sn_field(rec_words, 8, 3);
    step  = sn_field(rec_words, 11, 8);
    mask  = sn_field(rec_words, 35, SNOW_NCOMMIT);
    sn_log("T %d %c %d\r\n", round, STAGE_CH[stage & 7u], step);
    for (n = 0; n < SNOW_NN; n++) {
        unsigned o = SNOW_TRACE_HDRW + n * SNOW_TRACE_NS;
        cid = sn_field(rec_words, o, SNOW_CID_W);
        ptr = sn_field(rec_words, o + SNOW_CID_W, SNOW_PTR_W);
        fl  = sn_field(rec_words, o + SNOW_CID_W + SNOW_PTR_W, 6);
        if (cid == SNOW_RESET_CID)
            sn_log("N %d R %d %d %d %d %d %d\r\n", n,
                   fl & 1u, (fl >> 1) & 1u, (fl >> 2) & 1u, ptr,
                   (fl >> 3) & 1u, (fl >> 4) & 1u);
        else
            sn_log("N %d %d %d %d %d %d %d %d\r\n", n, cid,
                   fl & 1u, (fl >> 1) & 1u, (fl >> 2) & 1u, ptr,
                   (fl >> 3) & 1u, (fl >> 4) & 1u);
    }
    for (e = 0; e < SNOW_NE; e++) {
        g3 = sn_field(rec_words,
                      SNOW_TRACE_HDRW + SNOW_NN * SNOW_TRACE_NS + e * SNOW_TRACE_ES, 3);
        sn_log("E %d-%d %d %d\r\n", SNOW_EDGE_UV[e][0], SNOW_EDGE_UV[e][1],
               g3 & 3u, (g3 >> 2) & 1u);
    }
    if (stage == 1u && mask) {
        for (ci = 0; ci < SNOW_NCOMMIT; ci++)
            if ((mask >> ci) & 1u)
                sn_log("P %d-%d\r\n", SNOW_COMMIT_UV[ci][0], SNOW_COMMIT_UV[ci][1]);
    }
}
#endif

int main(void)
{
    unsigned round, cycles, nrec, rec, i, total = 0;

    /* Every diagnostic line starts with '#': the PC-side converter
     * (fpga_flow/board_records_to_trace.py, via board_log_check.py --mode 1)
     * parses the same file, and a line it cannot classify is a hard error --
     * which is the point.  Keep it that way when editing this program. */
    sn_log("# host: NN=%d NE=%d NCOMMIT=%d record=%d words mode=%d\r\n",
           SNOW_NN, SNOW_NE, SNOW_NCOMMIT, SNOW_TRACE_WORDS, SNOW_MODE);

    /* The core reset is generated INSIDE the PL (snowflake_reset_sync) and is
     * guaranteed to last RESET_LEN cycles, so the host only waits for STATUS[4]
     * to drop -- it never has to remember to reset the decoder. */
    while (sn_rd32(REG_STATUS) & SNOW_ST_CORE_RST)
        ;
    if (sn_check_id())
        return 1;

    for (round = 0; round < 12; round++) {
        cycles = sn_run_round(round, ROUNDS[round]);
        if (!cycles) return 1;
        nrec = sn_rd32(REG_REC_COUNT) & 0xFFFFu;
        if (sn_rd32(REG_STATUS) & SNOW_ST_REC_OVF) {
            sn_log("FATAL: round %d overflowed the record buffer\r\n", round);
            return 1;
        }
        sn_log("# round=%d records=%d cycles=%d\r\n", round, nrec, cycles);
        for (rec = 0; rec < nrec; rec++) {
            sn_fetch_record(rec);
            sn_emit(round, rec);
            total++;
        }
    }

    /* the correction output port: the last round's commit mask */
    sn_log("# commit mask:");
    for (i = 0; i < SNOW_CORR_WORDS; i++)
        sn_log(" %08x", sn_rd32(REG_CORR_BASE + 4u * i));
    sn_log("\r\n# total records=%d\r\n", total);
    sn_log("# DONE\r\n");
    return 0;
}
