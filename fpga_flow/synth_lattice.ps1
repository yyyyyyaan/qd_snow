#=====================================================================
# synth_lattice.ps1 -- synthesize the SHARED-LATTICE array for one config.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File synth_lattice.ps1 `
#       -Code surface -D 3 -Slices 2
#
# Why this exists instead of a plain sweep.ps1 call: the lattice RTL includes
# design/generated/snowflake_lattice.svh, whose contents are config-specific
# (SNOW_PE_STW depends on the direction count, SNOW_LAT_NSLOT on the box, ...).
# The generator must therefore run for the SAME config immediately before the
# sweep, otherwise Vivado parses a header from a different graph and fails with
# "part-select out of range" / "conditional expression could not be resolved".
#
# The ModelSim regression driver (msim_regress_lat.ps1) does the same two steps;
# this mirrors it for synthesis.
#
# !! THE VERIFY STEP BELOW IS NOT OPTIONAL !!
# A `surface d5` run once reported 754 LUT / 248 MHz because the header left on
# disk was still the `rep d3` one (NSLOT 8, ES 24): Vivado happily synthesized an
# 8/24 array and the job tag still claimed d5.  That "96.7% smaller" number was
# entirely an artifact.  Always confirm the header on disk matches the requested
# config BEFORE believing any area number.
#=====================================================================
param(
  [string] $Code    = 'rep',
  [int]    $D       = 3,
  [int]    $Slices  = 2,
  [string] $Dirs    = 'all',
  [string] $Part    = 'xcvu9p-flga2104-2L-e',
  [string] $Period  = '5.0',
  [string] $Mode    = 'synth'
)
$ErrorActionPreference = 'Continue'
$Flow = $PSScriptRoot
$Ws   = Split-Path -Parent $Flow
$Repo = Join-Path $Ws 'Helios_scalable_QEC-main\Helios_scalable_QEC-main'
$Lat  = Join-Path $Repo 'design\generated\snowflake_lattice.svh'
$Gra  = Join-Path $Repo 'design\generated\snowflake_graph.svh'

# 1. the graph header (same generator the other flows use)
Push-Location (Join-Path $Repo 'build_scripts')
python generate_snowflake.py --code $Code --d $D --dirs $Dirs | Out-Null
Pop-Location

# 2. the lattice header for THIS config, with SNOW_NCTX = $Slices
python (Join-Path $Flow 'make_lattice_sim.py') --code $Code --d $D `
        --slices $Slices --dirs $Dirs
if ($LASTEXITCODE -ne 0) { Write-Host "[lat] lattice generator FAILED"; exit 1 }

# 3. VERIFY the header on disk really is this configuration -------------------
# The header's own comment spells the code out ("repetition d=3, ..." for rep,
# "surface d=3, ..." for surface), so map the CLI code to that word first.
$codeWord = switch ($Code) {
  'rep'     { 'repetition' }
  'surface' { 'surface' }
  default   { $Code }
}
$hdr = (Get-Content $Lat -TotalCount 6) -join ' '
if ($hdr -notmatch ('\b' + [regex]::Escape($codeWord) + '\s+d=' + $D + '\b')) {
  Write-Host "[lat] ABORT: lattice header is not $Code ($codeWord) d=$D"
  Write-Host "      $hdr"
  exit 1
}
if ($hdr -notmatch ('\b' + $Slices + ' slices\b')) {
  Write-Host "[lat] ABORT: lattice header is not n=$Slices"
  Write-Host "      $hdr"
  exit 1
}
$latline = (Select-String -Path $Lat -Pattern 'NSLOT=\d+ node slots' | Select-Object -First 1).Line.Trim()
$grline  = (Select-String -Path $Gra -Pattern 'SNOW_NN\s*=|SNOW_NE\s*=' | Select-Object -First 2 |
            ForEach-Object { $_.Line.Trim() }) -join ' ; '
Write-Host ("[lat] header OK for {0} d={1} n={2}" -f $Code, $D, $Slices)
Write-Host ("      {0}" -f $latline)
Write-Host ("      {0}" -f $grline)

# 4. sweep one job (synth or impl)
$jobs = Join-Path $Flow ("jobs_lattice_one_{0}_d{1}_s{2}.txt" -f $Code, $D, $Slices)
@(
  "# generated by synth_lattice.ps1 -- one config only, so the lattice header",
  "# pinned by the generator above matches the top being synthesized.",
  ("{0} {1} 2:1 {2} {3} SNOW_LATTICE;SNOW_LAT" -f $Code, $D, $Part, $Period)
) | Set-Content -Encoding ASCII $jobs

$srcs = @(
  (Join-Path $Repo 'design\snowflake\snowflake_pe.sv'),
  (Join-Path $Repo 'design\snowflake\snowflake_edge.sv'),
  (Join-Path $Repo 'design\snowflake\snowflake_pe_array_lat.sv')
) -join ';'

& (Join-Path $Flow 'sweep.ps1') -JobsFile $jobs -Mode $Mode `
    -Top snowflake_pe_array_lat -Srcs $srcs -Slices $Slices
